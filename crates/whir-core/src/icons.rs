pub fn font(size: f32) -> FontId {
    FontId::new(size, FontFamily::Name(ICONS.into()))
}

/// Draw `icon` centred on `center`.
pub fn paint(painter: &Painter, center: Pos2, icon: Icon, size: f32, color: Color32) {
    painter.text(
        center,
        Align2::CENTER_CENTER,
        icon.glyph(),
        font(size),
        color,
    );
}

/// `icon` as text, for a stock button or label.
pub fn text(icon: Icon, size: f32) -> RichText {
    RichText::new(icon.glyph().to_string()).font(font(size))
}
